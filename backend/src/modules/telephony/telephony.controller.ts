import { Controller, Get, Post, Put, Delete, Body, Param, Query } from '@nestjs/common';
import { PrismaService } from '../../prisma/prisma.service';
import axios from 'axios';
import * as fs from 'fs';
import { exec } from 'child_process';

const PJSIP_CONF_PATH = '/www/wwwroot/vsms.ominaz.com/voice-pro/docker/asterisk/conf/pjsip.conf';

async function syncPjsipConf(prisma: PrismaService): Promise<boolean> {
  try {
    const trunks = await prisma.sipTrunk.findMany({
      where: { enabled: true },
    });

    let ini = '; ====================================================================\n';
    ini += '; Asterisk PJSIP Configuration (Auto-generated by VoicePro / VSMS)\n';
    ini += `; Last Updated: ${new Date().toISOString()}\n`;
    ini += '; ====================================================================\n\n';

    ini += '[global]\n';
    ini += 'type = global\n';
    ini += 'user_agent = VoiceBroadcastPro-Asterisk\n\n';

    ini += '[transport-udp]\n';
    ini += 'type = transport\n';
    ini += 'protocol = udp\n';
    ini += 'bind = 0.0.0.0:5060\n\n';

    ini += '[transport-tcp]\n';
    ini += 'type = transport\n';
    ini += 'protocol = tcp\n';
    ini += 'bind = 0.0.0.0:5060\n\n';

    ini += '; Outbound Trunk Template\n';
    ini += '[trunk-template](!)\n';
    ini += 'type = endpoint\n';
    ini += 'transport = transport-udp\n';
    ini += 'context = from-pstn\n';
    ini += 'disallow = all\n';
    ini += 'allow = alaw\n';
    ini += 'allow = ulaw\n';
    ini += 'allow = g729\n';
    ini += 'direct_media = no\n';
    ini += 'language = en\n\n';

    for (const trunk of trunks) {
      const name = trunk.name;
      const host = trunk.host;
      const port = trunk.port || 5060;
      const transport = trunk.transport || 'transport-udp';
      const codecs = (trunk.codecs || 'alaw,ulaw,g729').split(',').map((c) => c.trim()).filter(Boolean);

      ini += '; -----------------------------------------------------\n';
      ini += `; Trunk: ${name} (${trunk.type.toUpperCase()})\n`;
      ini += '; -----------------------------------------------------\n';

      if (trunk.type === 'registration' && trunk.username) {
        ini += `[${name}-auth]\n`;
        ini += 'type = auth\n';
        ini += 'auth_type = userpass\n';
        ini += `username = ${trunk.username}\n`;
        ini += `password = ${trunk.password || ''}\n\n`;

        ini += `[${name}-reg]\n`;
        ini += 'type = registration\n';
        ini += `outbound_auth = ${name}-auth\n`;
        ini += `server_uri = sip:${host}:${port}\n`;
        ini += `client_uri = sip:${trunk.username}@${host}:${port}\n`;
        ini += `contact_user = ${trunk.username}\n`;
        ini += 'retry_interval = 60\n\n';

        ini += `[${name}]\n`;
        ini += 'type = endpoint\n';
        ini += `transport = ${transport}\n`;
        ini += `context = ${trunk.context || 'from-pstn'}\n`;
        ini += 'disallow = all\n';
        for (const codec of codecs) {
          ini += `allow = ${codec}\n`;
        }
        ini += `outbound_auth = ${name}-auth\n`;
        ini += `aors = ${name}-aor\n`;
        ini += `from_user = ${trunk.username}\n`;
        ini += `from_domain = ${host}\n`;
        ini += 'direct_media = no\n';
        ini += 'rtp_symmetric = yes\n';
        ini += 'force_rport = yes\n';
        ini += 'rewrite_contact = yes\n\n';

        ini += `[${name}-aor]\n`;
        ini += 'type = aor\n';
        ini += `contact = sip:${host}:${port}\n\n`;
      } else {
        ini += `[${name}]\n`;
        ini += 'type = endpoint\n';
        ini += `transport = ${transport}\n`;
        ini += `context = ${trunk.context || 'from-pstn'}\n`;
        ini += 'disallow = all\n';
        for (const codec of codecs) {
          ini += `allow = ${codec}\n`;
        }
        ini += `aors = ${name}-aor\n`;
        ini += 'direct_media = no\n\n';

        ini += `[${name}-aor]\n`;
        ini += 'type = aor\n';
        ini += `contact = sip:${host}:${port}\n\n`;

        ini += `[${name}-identify]\n`;
        ini += 'type = identify\n';
        ini += `endpoint = ${name}\n`;
        ini += `match = ${host}\n\n`;
      }
    }

    fs.writeFileSync(PJSIP_CONF_PATH, ini, 'utf-8');
    exec('docker exec voice-pro-asterisk asterisk -rx "pjsip reload"', () => {});
    return true;
  } catch (e) {
    return false;
  }
}

@Controller('telephony')
export class TelephonyController {
  constructor(private prisma: PrismaService) {}

  // -------------------------------------------------------------
  // PBX Servers
  // -------------------------------------------------------------
  @Get('servers')
  async getServers() {
    return this.prisma.asteriskServer.findMany({
      include: { trunks: true, callers: true },
      orderBy: { createdAt: 'desc' },
    });
  }

  @Post('servers')
  async createServer(
    @Body()
    body: {
      name: string;
      ariBaseUrl: string;
      ariUsername: string;
      ariPassword: string;
      maxConcurrency?: number;
    },
  ) {
    return this.prisma.asteriskServer.create({
      data: {
        name: body.name,
        ariBaseUrl: body.ariBaseUrl,
        ariUsername: body.ariUsername,
        ariPassword: body.ariPassword,
        maxConcurrency: body.maxConcurrency || 100,
        isOnline: true,
        enabled: true,
      },
    });
  }

  // -------------------------------------------------------------
  // SIP Trunks (A to Z Legacy Features)
  // -------------------------------------------------------------
  @Get('trunks')
  async getTrunks() {
    return this.prisma.sipTrunk.findMany({
      include: {
        server: { select: { id: true, name: true, isOnline: true } },
        user: { select: { id: true, name: true, email: true } },
        callers: true,
      },
      orderBy: { createdAt: 'desc' },
    });
  }

  @Post('trunks')
  async createTrunk(
    @Body()
    body: {
      serverId: string;
      userId?: string;
      name: string;
      provider?: string;
      type?: string;
      host: string;
      port?: number;
      transport?: string;
      username?: string;
      password?: string;
      outboundCid?: string;
      codecs?: string;
      context?: string;
      maxConcurrency?: number;
      enabled?: boolean;
      notes?: string;
    },
  ) {
    const trunk = await this.prisma.sipTrunk.create({
      data: {
        serverId: body.serverId,
        userId: body.userId || null,
        name: body.name,
        provider: body.provider || 'custom',
        type: body.type || 'ip',
        host: body.host,
        port: body.port || 5060,
        transport: body.transport || 'transport-udp',
        username: body.username || null,
        password: body.password || null,
        outboundCid: body.outboundCid || null,
        codecs: body.codecs || 'alaw,ulaw,g729',
        context: body.context || 'from-pstn',
        maxConcurrency: body.maxConcurrency || 30,
        enabled: body.enabled !== undefined ? body.enabled : true,
        isOnline: true,
        notes: body.notes || null,
      },
    });

    await syncPjsipConf(this.prisma);
    return trunk;
  }

  @Put('trunks/:id')
  async updateTrunk(
    @Param('id') id: string,
    @Body()
    body: {
      serverId?: string;
      userId?: string;
      name?: string;
      provider?: string;
      type?: string;
      host?: string;
      port?: number;
      transport?: string;
      username?: string;
      password?: string;
      outboundCid?: string;
      codecs?: string;
      context?: string;
      maxConcurrency?: number;
      enabled?: boolean;
      notes?: string;
    },
  ) {
    const trunk = await this.prisma.sipTrunk.update({
      where: { id },
      data: {
        ...(body.serverId && { serverId: body.serverId }),
        ...(body.userId !== undefined && { userId: body.userId || null }),
        ...(body.name && { name: body.name }),
        ...(body.provider && { provider: body.provider }),
        ...(body.type && { type: body.type }),
        ...(body.host && { host: body.host }),
        ...(body.port && { port: body.port }),
        ...(body.transport && { transport: body.transport }),
        ...(body.username !== undefined && { username: body.username || null }),
        ...(body.password !== undefined && { password: body.password || null }),
        ...(body.outboundCid !== undefined && { outboundCid: body.outboundCid || null }),
        ...(body.codecs && { codecs: body.codecs }),
        ...(body.context && { context: body.context }),
        ...(body.maxConcurrency !== undefined && { maxConcurrency: body.maxConcurrency }),
        ...(body.enabled !== undefined && { enabled: body.enabled }),
        ...(body.notes !== undefined && { notes: body.notes || null }),
      },
    });

    await syncPjsipConf(this.prisma);
    return trunk;
  }

  @Delete('trunks/:id')
  async deleteTrunk(@Param('id') id: string) {
    const res = await this.prisma.sipTrunk.delete({
      where: { id },
    });
    await syncPjsipConf(this.prisma);
    return res;
  }

  // -------------------------------------------------------------
  // Callers (Caller IDs)
  // -------------------------------------------------------------
  @Get('callers')
  async getCallers() {
    return this.prisma.callerId.findMany({
      include: {
        server: { select: { id: true, name: true } },
        user: { select: { id: true, name: true, email: true } },
        sipTrunk: { select: { id: true, name: true, type: true, host: true } },
      },
      orderBy: { createdAt: 'desc' },
    });
  }

  @Post('callers')
  async createCaller(
    @Body()
    body: {
      serverId: string;
      userId?: string;
      sipTrunkId?: string;
      callerName: string;
      callerNumber: string;
      trunkName: string;
      maxConcurrency?: number;
      enabled?: boolean;
    },
  ) {
    return this.prisma.callerId.create({
      data: {
        serverId: body.serverId,
        userId: body.userId || null,
        sipTrunkId: body.sipTrunkId || null,
        callerName: body.callerName,
        callerNumber: body.callerNumber,
        trunkName: body.trunkName,
        maxConcurrency: body.maxConcurrency || 10,
        enabled: body.enabled !== undefined ? body.enabled : true,
        isOnline: true,
      },
    });
  }

  @Put('callers/:id')
  async updateCaller(
    @Param('id') id: string,
    @Body()
    body: {
      serverId?: string;
      userId?: string;
      sipTrunkId?: string;
      callerName?: string;
      callerNumber?: string;
      trunkName?: string;
      maxConcurrency?: number;
      enabled?: boolean;
    },
  ) {
    return this.prisma.callerId.update({
      where: { id },
      data: {
        ...(body.serverId && { serverId: body.serverId }),
        ...(body.userId !== undefined && { userId: body.userId || null }),
        ...(body.sipTrunkId !== undefined && { sipTrunkId: body.sipTrunkId || null }),
        ...(body.callerName && { callerName: body.callerName }),
        ...(body.callerNumber && { callerNumber: body.callerNumber }),
        ...(body.trunkName && { trunkName: body.trunkName }),
        ...(body.maxConcurrency !== undefined && { maxConcurrency: body.maxConcurrency }),
        ...(body.enabled !== undefined && { enabled: body.enabled }),
      },
    });
  }

  @Delete('callers/:id')
  async deleteCaller(@Param('id') id: string) {
    return this.prisma.callerId.delete({
      where: { id },
    });
  }

  // -------------------------------------------------------------
  // Manual PJSIP Sync
  // -------------------------------------------------------------
  @Post('sync-pjsip')
  async triggerPjsipSync() {
    const success = await syncPjsipConf(this.prisma);
    return { success, message: success ? 'PJSIP config synchronized and reloaded.' : 'PJSIP sync encountered an issue.' };
  }

  @Get('ping')
  async pingAri() {
    try {
      const server = await this.prisma.asteriskServer.findFirst();
      if (!server) return { online: false, error: 'No Asterisk server configured' };

      const auth = Buffer.from(`${server.ariUsername}:${server.ariPassword}`).toString('base64');
      const res = await axios.get(`${server.ariBaseUrl}/ari/asterisk/info`, {
        headers: { Authorization: `Basic ${auth}` },
        timeout: 3000,
      });

      return {
        online: true,
        system: res.data?.system?.entity_id || 'Asterisk PBX',
        version: res.data?.build?.version || '20.x',
      };
    } catch (err: any) {
      return { online: false, error: err.message };
    }
  }
}
